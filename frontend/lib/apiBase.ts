/**
 * Хөтчид ажиллаж буй хуудсанд API-гийн үндэс хаана байх вэ.
 *
 * Хариулт нь `/api/v1` — хуудсаа үйлчилсэн тэр л host дээр. Энэ нь гоо сайхны
 * сонголт биш, зөв байдлын нөхцөл: session cookie нь host-only тул үнэмлэхүй
 * хаяг өөр host руу заавал дуудлага cross-origin болж, cookie ОГТ илгээгдэхгүй.
 * API 401 буцааж, ажлын муж нэвтрэлт дууссан гэж үзээд `/login` руу түлхдэг.
 * Яг ийм зүйл тохиолдож байсан: native талд амжилттай нэвтэрсэн хэрнээ ажлын
 * мужид нэвтрэх дэлгэц гарч ирж байв.
 *
 * Өмнө нь энэ утга build үед шингэдэг байсан бөгөөд түүнийг зөвхөн
 * төхөөрөмжийн domain шугам дээр тойрдог байв. Тэр тойруу зам нь шинжийг нь
 * биш, шинж илэрсэн ганц газрыг л зассан байлаа: build-д шингэсэн хаяг нь
 * бүтээгдэхүүн хэрхэн харагдах (образын агуулга) ба хаана байрлах (суулгацын
 * хаяг) хоёрыг нэг утганд уядаг. Уясан үр дагавар нь нэг distribution-ы хоёр
 * суулгац хоёр өөр образ шаардана — тиймээс "нэг образ, өөр `.env`, зуун
 * суулгац" гэсэн Түвшин 1 боломжгүй болно. Апп сторыг Nexus дээр гаргахад
 * 1.53GB образыг ганцхан URL-ийн төлөө барих шаардлага гарсан нь үүний
 * бодит үнэ байв.
 *
 * Одоо production build нь `NEXT_PUBLIC_API_URL`-ийг огт тавихгүй. Тавьсан
 * үед л түүнийг хүндэтгэнэ — API нь үнэхээр өөр origin дээр байдаг цорын ганц
 * тохиолдол болох хөгжүүлэлт (frontend :3000, API :8080).
 */
const CONFIGURED = process.env.NEXT_PUBLIC_API_URL || "";

/**
 * Server талд харьцангуй зам утгагүй: origin гэж байхгүй.
 *
 * Өнөөдөр энэ салаагаар хэн ч ирдэггүй — API дуудагч бүр client component —
 * харин ирвэл хөгжүүлэлтийн хаяг нь буруу хариултаас дээр.
 */
const SERVER_FALLBACK = CONFIGURED || "http://localhost:8080/api/v1";

export function apiBase(): string {
  if (typeof window === "undefined") return SERVER_FALLBACK;
  return CONFIGURED || "/api/v1";
}
