-- Гарах дугтуйн `created_at` нь TIMESTAMPTZ биш, TEXT болов.
--
-- 00061 дээр `payload`-ыг яагаад JSONB биш TEXT болгосныг тайлбарласан:
-- гарын үсэг БАЙТУУДЫГ хамардаг, JSONB нь түлхүүрийн дарааллыг эмхэлдэг тул
-- хадгалаад буцааж уншихад өөр байт гарч ирнэ. Яг тэр дүгнэлт `created_at`
-- дээр хийгдээгүй байсан бөгөөд алдаа нь илүү нарийн:
--
--   * Go-гийн `time.Now()` НАНОсекунд өгдөг (Linux дээр; macOS дээр ихэвчлэн
--     микросекунд — тиймээс энэ алдаа хөгжүүлэгчийн машин дээр харагдалгүй,
--     CI дээр л илэрсэн);
--   * Postgres-ийн timestamptz нь МИКРОсекунд хүртэл хадгална;
--   * дугтуйг илгээхээр уншихад timestamptz-ээс мөр дахин дүрслэгдэж,
--     наносекундын оронтой гарын үсэг зурагдсан мөрөөс өөр болно.
--
-- Үр дүн: Linux дээр дугтуй БҮР гарын үсгийн шалгалтад унана. Сувагт юу ч
-- хүрэхгүй, шалтгаан нь "signature does not verify" гэсэн мөрөөс өөр юу ч
-- хэлэхгүй. Хамгийн муу хэлбэр: бүх зүйл зөв харагдаж, юу ч явахгүй.
--
-- Тиймээс энэ багана одооноос ГАРЫН ҮСЭГ ЗУРАГДСАН МӨРИЙГ ЯГ ТЭР ЧИГЭЭР нь
-- хадгална. Дахин дүрслэгдэхгүй тул дахин зөрөх боломжгүй.
--
-- Энэ багана SQL-д ашиглагддаггүй байсан гэдгийг тэмдэглэх нь зүйтэй: цорын
-- ганц уншигч нь дугтуйг эргүүлэн угсрах код байсан. SLA-г даалгаврын өөрийн
-- deadline, цэвэрлэгээг `queued_at` шийддэг. Өөрөөр хэлбэл timestamptz байх
-- шаардлага анхнаасаа байгаагүй.
--
-- ИРСЭН дугтуйн `urtuu_inbox.created_at` нь TIMESTAMPTZ ХЭВЭЭРЭЭ: түүнийг
-- хэзээ ч дахин дүрслэхгүй (гарын үсэг нь ирсэн байт дээр аль хэдийн
-- шалгагдсан), харин илгээгчийн цагаар SLA тооцоход агшин хэрэгтэй.

-- +goose Up

-- Хөрвүүлэлт нь хөгжүүлэлтийн мөрүүдэд зориулав: бодит ажиллагаанд энэ
-- хүснэгт хоосон (Өртөө хараахан ямар ч суулгац дээр асаагүй). Хуучин мөр
-- байсан ч наносекундын орон нь аль хэдийн алдагдсан тул хөрвүүлсэн ч
-- батлагдахгүй — тэдгээр нь гарын үсгээрээ унана, чимээгүй алдаа болохгүй.
ALTER TABLE urtuu_outbox
    ALTER COLUMN created_at TYPE TEXT
    USING to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"');

COMMENT ON COLUMN urtuu_outbox.created_at IS
    'Гарын үсэг зурагдсан RFC 3339 мөр, яг тэр чигээрээ. Дахин дүрслэхгүй.';

-- +goose Down
ALTER TABLE urtuu_outbox
    ALTER COLUMN created_at TYPE TIMESTAMPTZ USING created_at::timestamptz;
